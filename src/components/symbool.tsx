type Props = Omit<SymbolViewProps, "name"> & { name: SFSymbol };

/** SymbolView die ook op Android en het web een icoon toont. Gebruik dit in plaats van SymbolView. */
export function Symbool({ name, ...rest }: Props) {
  const md = SF_NAAR_MATERIAL[name];
  if (__DEV__ && !md) console.warn(`[Symbool] geen Material-icoon voor "${name}": voeg het toe in symbool.tsx`);
  return <SymbolView name={{ ios: name, android: md, web: md }} {...rest} />;
}
